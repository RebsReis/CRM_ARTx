"""Integration tests in a disposable PostgreSQL schema, never in public tables.

Run from backend: ../.venv/Scripts/python.exe -m unittest test_prospeccoes -v
"""
import unittest
from concurrent.futures import ThreadPoolExecutor
from datetime import datetime
from pathlib import Path
from uuid import uuid4
from unittest.mock import patch

from fastapi import HTTPException
from sqlalchemy import create_engine, select, text, func
from sqlalchemy.orm import sessionmaker

import main
from database import engine
from models import Base, Lead, HistoricoLead, Meta
from schemas import LeadCreate, LeadFaseUpdate


class ProspeccoesPostgresTest(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.schema = "test_prospeccoes_" + uuid4().hex
        with engine.begin() as connection:
            definition = connection.execute(text("SELECT pg_get_functiondef('public.registrar_historico_lead()'::regprocedure)")).scalar_one()
            connection.execute(text(f'CREATE SCHEMA "{cls.schema}"'))
        cls.test_engine = create_engine(engine.url, connect_args={"options": f"-csearch_path={cls.schema}"})
        cls.sessions = sessionmaker(bind=cls.test_engine)
        try:
            Base.metadata.create_all(cls.test_engine)
            with cls.test_engine.begin() as connection:
                definition = definition.replace("FUNCTION public.registrar_historico_lead()", f'FUNCTION "{cls.schema}".registrar_historico_lead()')
                connection.execute(text(definition))
                connection.execute(text("CREATE TRIGGER trigger_historico_lead BEFORE UPDATE ON leads FOR EACH ROW EXECUTE FUNCTION registrar_historico_lead()"))
        except Exception:
            cls.tearDownClass()
            raise

    @classmethod
    def tearDownClass(cls):
        cls.test_engine.dispose()
        # Only the schema generated by this test can be dropped.
        assert cls.schema.startswith("test_prospeccoes_") and len(cls.schema) == 49
        with engine.begin() as connection:
            connection.execute(text(f'DROP SCHEMA "{cls.schema}" CASCADE'))

    def novo(self, fase="PROSPECTAR"):
        with patch.object(main, "SessionLocal", self.sessions):
            lead = main.criar_lead(LeadCreate(nome_empresa="Teste de prospeccao", fase=fase))
            return lead.id

    def mover(self, lead_id, fase):
        with self.sessions() as db:
            return main.atualizar_fase_lead(lead_id, LeadFaseUpdate(fase=fase), db)

    def total(self, ano, mes):
        with self.sessions() as db:
            return main.consultar_prospeccoes_mensais(ano, mes, db)["prospeccoes_realizadas"]

    def data(self, lead_id):
        with self.sessions() as db:
            return db.get(Lead, lead_id).prospectado_em

    def test_ciclo_completo_persistencia_e_mes(self):
        with self.sessions() as db:
            hoje = db.scalar(select(func.localtimestamp()))
        antes = self.total(hoje.year, hoje.month)
        lead_id = self.novo()
        self.assertIsNone(self.data(lead_id))
        self.assertEqual(self.total(hoje.year, hoje.month), antes)
        self.mover(lead_id, "PROSPECTAR")
        self.assertIsNone(self.data(lead_id))
        self.mover(lead_id, "FOLLOW_UP")
        primeira = self.data(lead_id)
        self.assertIsNotNone(primeira)
        self.assertEqual(self.total(primeira.year, primeira.month), antes + 1)
        for fase in ["REUNIAO_MARCADA", "PROSPECTAR", "FOLLOW_UP", "FOLLOW_UP"]:
            self.mover(lead_id, fase)
            self.assertEqual(self.data(lead_id), primeira)
            self.assertEqual(self.total(primeira.year, primeira.month), antes + 1)
        with self.sessions() as db:
            meta = db.scalar(select(Meta).where(Meta.ano == primeira.year, Meta.mes == primeira.month))
            if meta is None:
                db.add(Meta(ano=primeira.year, mes=primeira.month, meta_prospeccoes=100, meta_reunioes=10, meta_faturamento=1000))
                db.commit()
            painel = main.dashboard_metas(primeira.year, primeira.month, db)
            self.assertEqual(painel["prospeccoes"]["prospeccoes_realizadas"], main.contar_leads_no_funil(db, ["FOLLOW_UP", "REUNIAO_MARCADA", "REMARKETING_FUTURO"]))

    def test_outras_saidas_e_cadastro_fora_de_prospectar(self):
        for fase in ["REUNIAO_MARCADA", "REMARKETING_FUTURO"]:
            lead_id = self.novo()
            self.mover(lead_id, fase)
            self.assertIsNotNone(self.data(lead_id))
        lead_id = self.novo("FOLLOW_UP")
        self.mover(lead_id, "REUNIAO_MARCADA")
        self.assertIsNone(self.data(lead_id))

    def test_endpoint_manual_nao_antecipa_e_e_idempotente(self):
        lead_id = self.novo()
        with self.sessions() as db:
            with self.assertRaises(HTTPException) as error:
                main.registrar_prospeccao(lead_id, db)
            self.assertEqual(error.exception.status_code, 409)
        self.assertIsNone(self.data(lead_id))
        self.mover(lead_id, "FOLLOW_UP")
        primeira = self.data(lead_id)
        with self.sessions() as db:
            self.assertFalse(main.registrar_prospeccao(lead_id, db)["contabilizado_agora"])
        self.assertEqual(self.data(lead_id), primeira)

    def test_movimentos_concorrentes(self):
        lead_id = self.novo()
        with ThreadPoolExecutor(max_workers=2) as executor:
            futures = [executor.submit(self.mover, lead_id, fase) for fase in ["FOLLOW_UP", "REMARKETING_FUTURO"]]
            for future in futures:
                future.result(timeout=30)
        with self.sessions() as db:
            saidas = db.scalar(select(func.count(HistoricoLead.id)).where(HistoricoLead.lead_id == lead_id, HistoricoLead.fase_anterior == "PROSPECTAR"))
            primeira = main.primeira_prospeccao_historica(db, lead_id)
        self.assertEqual(saidas, 1)
        self.assertEqual(self.data(lead_id), primeira)

    def test_rollback_nao_grava_metade_da_transicao(self):
        lead_id = self.novo()
        with self.sessions() as db:
            with patch.object(db, "commit", side_effect=RuntimeError("falha simulada")):
                with self.assertRaises(HTTPException):
                    main.atualizar_fase_lead(lead_id, LeadFaseUpdate(fase="FOLLOW_UP"), db)
        with self.sessions() as db:
            lead = db.get(Lead, lead_id)
            self.assertEqual(lead.fase, "PROSPECTAR")
            self.assertIsNone(lead.prospectado_em)
            self.assertIsNone(main.primeira_prospeccao_historica(db, lead_id))

    def test_recuperacao_historica_idempotente(self):
        lead_id = self.novo("FOLLOW_UP")
        primeira = datetime(2024, 12, 31, 23, 59)
        antes = self.total(2024, 12)
        with self.sessions() as db:
            db.add_all([HistoricoLead(lead_id=lead_id, fase_anterior="PROSPECTAR", fase_nova="FOLLOW_UP", movimentado_em=primeira), HistoricoLead(lead_id=lead_id, fase_anterior="PROSPECTAR", fase_nova="FOLLOW_UP", movimentado_em=datetime(2025, 1, 1))])
            db.commit()
        sql = Path(__file__).with_name("migrations").joinpath("20261016_primeira_prospeccao.sql").read_text()
        for _ in range(2):
            with self.test_engine.begin() as connection:
                connection.execute(text(sql))
            self.assertEqual(self.data(lead_id), primeira)
            self.assertEqual(self.total(2024, 12), antes + 1)
        self.mover(lead_id, "PROSPECTAR")
        self.mover(lead_id, "FOLLOW_UP")
        self.assertEqual(self.data(lead_id), primeira)


if __name__ == "__main__":
    unittest.main()
